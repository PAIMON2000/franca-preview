using System.IO;
using System.Text;

namespace Franca.Services;

// 游戏译文目录同步（lab/010 Slice 2）：把游戏包译文写成 XUnity 静态译文文件
// BepInEx/Translation\<lang>\Text\Franca.txt（原文=译文，每行一条），XUnity 文件监视触发运行时重载。
// 关键设计：词典条目绝不写入——词典译文必须继续走中继请求，否则 XUnity 静态加载后
// 中继收不到该文本的请求，后台在线升级链路就断了。词典只负责"第一次在线翻译的结果固化"，
// 升级来源永远是中继请求。
public sealed class GameTextSyncService
{
    // 升级通知合并窗口：窗口内连续通知合并为一次追加写，避免高频写入触发重载风暴
    private static readonly TimeSpan FlushWindow = TimeSpan.FromSeconds(1);

    private readonly object _sync = new();
    private int _activeAppId;
    private string _activeGameDir = "";
    private string _activeLang = "";
    private Dictionary<string, string> _pending = new(StringComparer.Ordinal);
    private CancellationTokenSource? _flushCts;
    private long _writeCount;

    // 成功写盘次数（全量 + 追加），供状态页展示升级链路活动
    public long WriteCount => Interlocked.Read(ref _writeCount);

    public static string TextFilePath(string gameDir, string xunityLang) =>
        Path.Combine(gameDir, "BepInEx", "Translation", xunityLang, "Text", "Franca.txt");

    // 激活当前游戏：此后只接受该 appId 的升级通知；切换到新游戏时旧缓冲整体丢弃
    public void Activate(int appId, string gameDir, string xunityLang)
    {
        lock (_sync)
        {
            _activeAppId = appId;
            _activeGameDir = gameDir;
            _activeLang = xunityLang;
            _pending.Clear();
            _flushCts?.Cancel();
            _flushCts = null;
        }
    }

    public void Deactivate(int appId)
    {
        lock (_sync)
        {
            if (appId != _activeAppId) return;
            _activeAppId = 0;
            _activeGameDir = "";
            _pending.Clear();
            _flushCts?.Cancel();
            _flushCts = null;
        }
    }

    // 游戏启动前全量重写 Franca.txt（仅游戏包条目，后写优先；排序输出保证内容确定）。
    // 全量重写会清掉运行期追加的升级行，但升级结果同包条目重复，Prepare 后由后台升级再补，无损。
    public Task PrepareForGameAsync(PackStore packs, int appId, string packLang,
        string gameDir, string xunityLang, CancellationToken ct = default)
    {
        var builder = new StringBuilder();
        foreach (var (src, tgt) in packs.EnumerateEntries(appId, packLang))
        {
            if (src.Length == 0 || tgt.Length == 0) continue;
            builder.Append(Escape(src)).Append('=').Append(Escape(tgt)).Append('\n');
        }
        return WriteFileAsync(TextFilePath(gameDir, xunityLang), builder.ToString(), ct);
    }

    // 中继后台升级完成通知（RelayServer.UpgradeCompleted）：非当前激活游戏的通知按 appId 丢弃；
    // 当前游戏的进缓冲，FlushWindow 后合并追加写入 Franca.txt
    public void NotifyUpgrade(int appId, string src, string tgt)
    {
        CancellationTokenSource timer;
        lock (_sync)
        {
            if (appId != _activeAppId || _activeGameDir.Length == 0) return;
            if (src.Length == 0 || tgt.Length == 0) return;
            _pending[src] = tgt;
            _flushCts?.Cancel();
            timer = new CancellationTokenSource();
            _flushCts = timer;
        }
        _ = FlushAfterDelayAsync(timer);
    }

    private async Task FlushAfterDelayAsync(CancellationTokenSource timer)
    {
        List<KeyValuePair<string, string>> batch;
        string gameDir, lang;
        try
        {
            await Task.Delay(FlushWindow, timer.Token);
            lock (_sync)
            {
                if (timer.IsCancellationRequested) return;
                batch = _pending.ToList();
                _pending.Clear();
                _flushCts = null;
                gameDir = _activeGameDir;
                lang = _activeLang;
            }
        }
        catch (OperationCanceledException)
        {
            return; // 被更新的通知取代或游戏切换，由后继定时器负责
        }
        var builder = new StringBuilder();
        foreach (var (src, tgt) in batch)
            builder.Append(Escape(src)).Append('=').Append(Escape(tgt)).Append('\n');
        await WriteFileAsync(TextFilePath(gameDir, lang), builder.ToString(), CancellationToken.None, append: true);
    }

    // 全量写走临时文件+移动（避免游戏读到半截文件）；追加写仅用于运行期升级行。
    // 写失败记 AppLog 不抛：译文目录同步是增强链路，翻译主流程不依赖它。
    private async Task WriteFileAsync(string path, string content, CancellationToken ct, bool append = false)
    {
        try
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            // XUnity 5.6.2 prunes its default output file on a translation-directory change,
            // even before its first translation has created that file. Publish it before Franca.txt.
            // Never truncate an existing runtime cache, including when the game creates it concurrently.
            var runtimeCache = Path.Combine(Path.GetDirectoryName(path)!, "_AutoGeneratedTranslations.txt");
            if (!File.Exists(runtimeCache))
            {
                try
                {
                    using var empty = new FileStream(runtimeCache, FileMode.CreateNew, FileAccess.Write, FileShare.ReadWrite);
                }
                catch (IOException) when (File.Exists(runtimeCache)) { }
            }
            if (append && File.Exists(path))
            {
                await File.AppendAllTextAsync(path, content, new UTF8Encoding(false), ct);
                Interlocked.Increment(ref _writeCount);
                return;
            }
            var temporary = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
            try
            {
                await File.WriteAllTextAsync(temporary, content, new UTF8Encoding(false), ct);
                File.Move(temporary, path, overwrite: true);
                Interlocked.Increment(ref _writeCount);
            }
            finally
            {
                if (File.Exists(temporary)) File.Delete(temporary);
            }
        }
        catch (Exception ex)
        {
            AppLog.Write($"Franca.txt write failed: {ex.Message}");
        }
    }

    // XUnity 译文文件的换行持久化为字面 "\n" 两字符（对齐其 _AutoGeneratedTranslations.txt 转义惯例）
    private static string Escape(string text) =>
        text.Replace("\r\n", "\n").Replace("\r", "\n").Replace("\n", "\\n");
}
